#!/usr/bin/env python3
"""Regenerate every setup script from the plain source files (one file, the
same in every repository that uses it).

    python3 tools/build.py          # rewrite the generated scripts
    python3 tools/build.py --check  # exit 1 if any generated script is out of date

A MODULE is any top-level folder with a module.toml (format: tools/README.md):

    <module>/module.toml        what the module makes or changes, and its settings
    <module>/src/setup.sh.in    the script that runs inside qubes (one role per qube)
    <module>/src/*              files installed inside qubes, embedded verbatim

From each module it generates, as its module.toml asks:

    <module>/setup.sh                    run inside a qube (for the mostly-GUI route)
    <module>/setup-dom0.sh               dom0, everything; no minimal templating needed
    <module>/setup-dom0-templating.sh    dom0, for a system with minimal templating

and, when templating/ is present (the 'qubes' repository):

    templating/install.sh       minimal templating on its own (dom0)
    setup-all-in-one.sh         minimal templating + a question for every module (dom0)

Every generated script embeds its sources verbatim, so what you audit in the
sources is exactly what runs.
"""
import glob
import os
import re
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTE = "# GENERATED by tools/build.py from the plain files beside it: edit those, then rebuild.\n"
STANDALONE_BASE = "fedora-44-minimal"
STANDALONE_PREFIX = "fedora-44-"     # standalone templates: fedora-44-<qube>
MT_PREFIX = "f44-"                   # minimal templating: f44-<qube>
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
PKG_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")
PATH_RE = re.compile(r"^/[A-Za-z0-9_./-]+$")
KINDS = {"app", "named-disposable"}
QUBE_KEYS = {"name", "kind", "dvm", "packages", "label", "dvm_label", "memory", "netvm", "firewall",
             "shutdown_timeout", "menu", "role", "dvm_role", "keep"}
TOP_KEYS = {"title", "description", "question", "order", "versions", "target", "qube", "policy", "done"}


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        content = f.read()
    assert content.endswith("\n"), f"{rel} must end with a newline"
    return content


def embed(var, content):
    d = f"__END_{var}__"
    assert d not in content, var
    return f"{var}=$(cat <<'{d}'\n{content}{d}\n)\n"


def var(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def heredoc_str(s):
    """Text for an unquoted heredoc, with {qube} placeholders turned into variables."""
    s = s.replace("\\", "\\\\").replace("$", "\\$").replace("`", "\\`")
    return re.sub(r"\{([A-Za-z0-9_.-]+)\}", lambda m: "${Q_" + var(m.group(1)) + "}", s)


def tplv(q):
    return f'"$TPL_PREFIX${{Q_{var(q["name"])}}}"'


def bash_str(s):
    """Text for inside double quotes in bash, with {qube} placeholders turned
    into that qube's CONFIG variable."""
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`")
    return re.sub(r"\{([A-Za-z0-9_.-]+)\}", lambda m: "${Q_" + var(m.group(1)) + "}", s)


# ================================================================== modules
class Module:
    def __init__(self, folder):
        self.folder = folder
        self.name = folder
        with open(os.path.join(ROOT, folder, "module.toml"), "rb") as f:
            m = tomllib.load(f)
        bad = set(m) - TOP_KEYS
        assert not bad, f"{folder}/module.toml: unknown keys {bad}"
        self.title = m["title"]
        self.description = m.get("description", "")
        self.question = m.get("question")
        self.order = m.get("order", 100)
        self.versions = m.get("versions", ["setup"])
        assert set(self.versions) <= {"setup", "dom0", "dom0-templating"}, folder
        self.target = m.get("target")
        self.qubes = m.get("qube", [])
        self.policy = m.get("policy")
        self.done = m.get("done", "").strip("\n")
        assert bool(self.target) != bool(self.qubes), f"{folder}: give either [target] or [[qube]]"
        names = set()
        for q in self.qubes:
            assert set(q) <= QUBE_KEYS, f"{folder}: unknown keys {set(q) - QUBE_KEYS}"
            assert q["kind"] in KINDS, f"{folder}: kind must be one of {KINDS}"
            assert (q["kind"] == "named-disposable") == ("dvm" in q), f"{folder}: dvm goes with named-disposable"
            for n in [q["name"], q.get("dvm", "")]:
                if n:
                    assert NAME_RE.match(n) and n not in names, f"{folder}: bad or repeated name {n}"
                    names.add(n)
            for p in q.get("packages", []):
                assert PKG_RE.match(p), f"{folder}: bad package {p}"
            for p in q.get("keep", []):
                assert PATH_RE.match(p), f"{folder}: bad path {p}"
        self.names = names
        if self.target:
            t = self.target
            assert t["kind"] in ("TemplateVM", "dvm") and (t["qube"] == "@base" or NAME_RE.match(t["qube"])), folder
        # the in-qube script
        srcdir = os.path.join(ROOT, folder, "src")
        files = sorted(f for f in os.listdir(srcdir) if os.path.isfile(os.path.join(srcdir, f))
                       and not f.endswith((".in", ".pyc")) and not f.startswith("."))
        parts = "".join(embed("F_" + var(f), read(f"{folder}/src/{f}")) for f in files)
        t = read(f"{folder}/src/setup.sh.in")
        assert t.count("@@NOTE@@") == 1 and t.count("@@EMBED@@\n") == 1, f"{folder}/src/setup.sh.in"
        t = t.replace("@@NOTE@@", NOTE).replace("@@EMBED@@\n", parts)
        for q in self.qubes:
            t = t.replace(f"@@PACKAGES:{q['name']}@@", " ".join(q.get("packages", [])))
        assert "@@" not in t, f"{folder}/src/setup.sh.in: unknown @@ placeholder"
        self.setup = t
        self.v = var(folder)            # bash name for this module

    # ------------------------------------------------------------ shared bits
    def config(self):
        lines = []
        for q in self.qubes:
            lines.append(f"Q_{var(q['name'])}={q['name']}")
            if q.get("dvm"):
                lines.append(f"Q_{var(q['dvm'])}={q['dvm']}")
        return "\n".join(lines) + "\n"

    def qv(self, name):
        return "$Q_" + var(name)

    def all_names(self):
        out = []
        for q in self.qubes:
            out += [self.qv(q["name"])] + ([self.qv(q["dvm"])] if q.get("dvm") else [])
        return out

    def funcs(self, templating):
        """bash functions for this module. templating=True: minimal templating
        builds the templates and qubes; False: this script makes them."""
        v, out = self.v, []
        if self.target:
            t = self.target
            out.append(f'''{v}_run() {{   # {v}_run <qube>: {self.title}
    say "   running {self.name}/setup.sh in $1"
    run_setup "$S_{v}" "$1" {bash_args(t.get("args", ""))} || {{ rc=$?; [ "$rc" -eq 3 ] || die "{self.name}/setup.sh failed in $1 (exit $rc)"; warn "{self.name}: finished with a warning (see above)"; }}
}}
''')
            return "".join(out)

        names = " ".join(f'"{n}"' for n in self.all_names())
        out.append(f'{v}_check() {{ local n; for n in {names}; do valid_name "$n"; done; }}\n')

        # ---- clear the way (before templates are built or qubes made)
        body = []
        for q in self.qubes:
            for p in q.get("keep", []):
                holder = q.get("dvm") or q["name"]
                body.append(f'    KEEP["{holder}:{p}"]=$(save_file {self.qv(holder)} {p})')
        for q in self.qubes:
            if q["kind"] == "named-disposable":
                body.append(f'    make_way {self.qv(q["name"])} DispVM recreate')
                body.append(f'    make_way {self.qv(q["dvm"])} dvm recreate')
        for q in self.qubes:
            if q["kind"] == "app":
                body.append(f'    make_way {self.qv(q["name"])} AppVM keep')
        for q in self.qubes:
            body.append(f'    make_way {tplv(q)} TemplateVM keep')
        out.append(f"{v}_clear() {{\n" + "\n".join(body) + "\n}\n")

        if templating:
            # ---- base packages, lists, master.dnf, templates.conf
            pk = sorted({p for q in self.qubes for p in q.get("packages", [])})
            body = [f'    in_vm "$BASE" "dnf -y install {" ".join(pk)}"' if pk else "    :",
                    f'    add_to_master "{self.title}" {" ".join(pk)}' if pk else ""]
            for q in self.qubes:
                pkgs = " ".join(q.get("packages", []))
                body.append(f'    write_list {self.qv(q["name"])} "{self.title}" {pkgs}')
            out.append(f"{v}_base() {{   # in the base template, while it runs\n" +
                       "\n".join(b for b in body if b) + "\n}\n")
            body = []
            for q in self.qubes:
                dvm = self.qv(q["dvm"]) if q.get("dvm") else '""'
                body.append(f'    set_section "$TPL_PREFIX${{Q_{var(q["name"])}}}" {dvm} {self.qv(q["name"])}')
            out.append(f"{v}_conf() {{\n" + "\n".join(body) + "\n}\n")
            tpls = " ".join(f'"$TPL_PREFIX${{Q_{var(q["name"])}}}"' for q in self.qubes)
            out.append(f"{v}_templates() {{ echo {tpls}; }}\n")
        else:
            # ---- standalone: templates and qubes made here
            body = []
            for q in self.qubes:
                tpl = f'"$TPL_PREFIX${{Q_{var(q["name"])}}}"'
                pk = " ".join(q.get("packages", []))
                body.append(f'    make_template {tpl}{" " + pk if pk else ""}')
            for q in self.qubes:
                tpl = f'"$TPL_PREFIX${{Q_{var(q["name"])}}}"'
                if q["kind"] == "named-disposable":
                    body.append(f'    qvm-create --class AppVM --template {tpl} --label {q.get("dvm_label", "black")} {self.qv(q["dvm"])}')
                    body.append(f'    qvm-prefs {self.qv(q["dvm"])} template_for_dispvms True')
                    body.append(f'    say "   made {q["dvm"]} (disposable template on $TPL_PREFIX${{Q_{var(q["name"])}}})"')
                    body.append(f'    qvm-create --class DispVM --template {self.qv(q["dvm"])} --label {q.get("label", "red")} {self.qv(q["name"])}')
                    body.append(f'    say "   made {q["name"]} (named disposable on {q["dvm"]})"')
                else:
                    n = self.qv(q["name"])
                    body.append(f'    if exists {n}; then qvm-prefs {n} template {tpl}; say "   kept {q["name"]} (your data stays), on $TPL_PREFIX${{Q_{var(q["name"])}}}"')
                    body.append(f'    else qvm-create --class AppVM --template {tpl} --label {q.get("label", "red")} {n}; say "   made {q["name"]} (app qube)"; fi')
            out.append(f"{v}_make() {{\n" + "\n".join(body) + "\n}\n")

        # ---- settings, in-qube setup, policy (after the qubes exist)
        body = []
        for q in self.qubes:
            n, desc = self.qv(q["name"]), []
            if "label" in q:
                body.append(f'    qvm-prefs {n} label {q["label"]}')
                desc.append(f'label {q["label"]}')
            if q.get("dvm"):
                body.append(f'    qvm-prefs {self.qv(q["dvm"])} label {q.get("dvm_label", "black")}')
            if "memory" in q:
                body.append(f'    qvm-prefs {n} memory {int(q["memory"])}')
                desc.append(f'{int(q["memory"])} MB initial memory')
            if "netvm" in q:
                nv = "''" if q["netvm"] == "none" else self.qv(q["netvm"]) if q["netvm"] in self.names else q["netvm"]
                body.append(f'    qvm-prefs {n} netvm {nv}')
                desc.append("no network" if q["netvm"] == "none" else f"netvm {q['netvm']}")
            if "firewall" in q:
                rules = [fw_rule(r) for r in q["firewall"]]
                body.append(f'    set_firewall {n} ' + " ".join(f'"{r}"' for r in rules))
                desc.append("firewall " + " + ".join(q["firewall"]) + " only")
            if "shutdown_timeout" in q:
                body.append(f'    qvm-prefs {n} shutdown_timeout {int(q["shutdown_timeout"])}')
                desc.append(f'shutdown timeout {int(q["shutdown_timeout"])}s')
            if desc:
                body.append(f'    say "   {q["name"]}: {", ".join(desc)}"')
            if "menu" in q:
                body.append(f'    set_menu {n} {" ".join(q["menu"])}')
            if q["kind"] == "named-disposable" and "netvm" not in q:
                body.append(f'    [ -n "$(qvm-prefs {n} netvm)" ] || warn "{q["name"]} has no netvm: set its networking in Qube Settings"')
        for q in self.qubes:
            if q.get("dvm_role"):
                d = self.qv(q["dvm"])
                body.append(f'    say "   {self.name}/setup.sh {q["dvm_role"].split()[0]} in {q["dvm"]}"')
                body.append(f'    run_setup "$S_{v}" {d} {bash_args(q["dvm_role"])}')
                for p in q.get("keep", []):
                    body.append(f'    restore_file {d} {p} "${{KEEP["{q["dvm"]}:{p}"]:-}}"')
                body.append(f'    qvm-shutdown --wait {d}')
        if self.policy:
            pol = self.policy
            path = "/etc/qubes/policy.d/" + pol["file"]
            lines = [f"# {path} - written by the {self.name} setup ({self.title})"] + pol["lines"]
            for old in pol.get("replaces", []):
                body.append(f'    remove_old_policy "/etc/qubes/policy.d/{old}"')
            body.append(f'    write_policy "{path}" ' + " ".join(f'"{bash_str(l)}"' for l in lines))
        for q in self.qubes:
            if q.get("role"):
                n = self.qv(q["name"])
                body.append(f'    say "   {self.name}/setup.sh {q["role"].split()[0]} in {q["name"]} (starts it)"')
                body.append(f'    run_setup "$S_{v}" {n} {bash_args(q["role"])} || {{ rc=$?; [ "$rc" -eq 3 ] || die "setting up {q["name"]} failed (exit $rc)"; WARNED=1; }}')
        out.append(f"{v}_finish() {{\n" + "\n".join(body) + "\n}\n")
        return "".join(out)

    def done_text(self):
        return heredoc_str(self.done) if self.done else ""


def bash_args(s):
    return " ".join(bash_str(w) if "{" not in w else f'"{bash_str(w)}"' for w in s.split())


def fw_rule(r):
    w = r.split()
    if w == ["dns"]:
        return "specialtarget=dns"
    if len(w) == 2 and w[0] in ("tcp", "udp") and w[1].isdigit():
        return f"proto={w[0]} dstports={w[1]}"
    raise SystemExit(f"unknown firewall rule {r!r}: use 'dns', 'tcp PORT' or 'udp PORT'")


# ================================================================== dom0 scripts for one module
def header(path, m, what, usage_extra=""):
    return f'''#!/bin/bash
# {path} - {m.title}: {m.description}
# {what}
{NOTE}#
#   bash {os.path.basename(path)}          asks once, then runs to the end
#   bash {os.path.basename(path)} --yes    no question
{usage_extra}'''


EXISTING_RULES = '''#
# Qubes that already exist (rules in the shared helpers below):
#   wrong kind                      kept as <name>-old, and a new one made
#   named disposables and their
#   disposable templates            removed and made again (nothing of yours in them;
#                                   the files listed as kept are carried over)
#   app qubes                       kept with your data; their settings are set again
#   templates                       kept and updated
'''


def describe_qubes(m, prefix):
    out = []
    for q in m.qubes:
        tpl = prefix + q["name"]
        pk = ", ".join(q.get("packages", [])) or "nothing extra"
        if q["kind"] == "named-disposable":
            out.append(f"#   {tpl}: template, base + {pk}")
            out.append(f"#   {q['dvm']}: disposable template on it")
            out.append(f"#   {q['name']}: named disposable on {q['dvm']}")
        else:
            out.append(f"#   {tpl}: template, base + {pk}")
            out.append(f"#   {q['name']}: app qube on it")
    if m.policy:
        out.append(f"#   /etc/qubes/policy.d/{m.policy['file']}: " + "; ".join(m.policy["lines"]))
    return "\n".join(out) + "\n"


def confirm_block(m, lines):
    shut = ", ".join(n for q in m.qubes for n in [q["name"]] + ([q["dvm"]] if q.get("dvm") else []))
    echo = "\n".join(f'    echo "  {l}"' for l in lines if l)
    return f'''if [ "${{1:-}}" != --yes ]; then
    echo "{bash_str(m.title)}. This will:"
{echo}
    echo "It shuts down {shut} if running (save open files in them first)."
    read -r -p "Continue? [y/N] " a
    [[ $a =~ ^[Yy] ]] || {{ echo "cancelled, nothing changed"; exit 1; }}
fi
'''


OLD_NOTE = """Qubes kept as <name>-old (if any were listed above) can be deleted once you
don't need them: qvm-remove <name>-old
"""


def done_block(m):
    t = m.done_text()
    return f'''
echo
echo "Done."
[ "$WARNED" -eq 0 ] || echo "  Finished with a warning: see the messages above."
cat <<EOF
{t + chr(10) if t else ""}{OLD_NOTE if m.qubes else ""}EOF
'''


def module_dom0(m):
    path = f"{m.folder}/setup-dom0.sh"
    if m.target:
        t = m.target
        default = STANDALONE_BASE if t["qube"] == "@base" else t["qube"]
        kind = "template" if t["kind"] == "TemplateVM" else "disposable template"
        s = header(path, m, f"Runs {m.folder}/setup.sh in a {kind} ({default} by default) from dom0. "
                   "Works with or without minimal templating.") + f'''#
# Set TARGET below to use another {kind}. Re-running is safe.

set -euo pipefail

# ------------------------------------------------------------------ CONFIG
TARGET={default}
# ------------------------------------------------------------------ END CONFIG
WARNED=0

{embed("S_" + m.v, m.setup)}{read("tools/dom0-lib.sh")}{m.funcs(False)}
[ "$(id -u)" -ne 0 ] || die "run as your normal user in dom0, not as root"
command -v qvm-prefs >/dev/null || die "run this in dom0"
valid_name "$TARGET"
exists "$TARGET" || die "$TARGET not found: set TARGET at the top of this script"
[ "$(kind "$TARGET")" = {t["kind"]} ] || die "$TARGET is a $(describe "$(kind "$TARGET")"), not a {kind}"
if [ "${{1:-}}" != --yes ]; then
    echo "{bash_str(m.title)}: runs {m.folder}/setup.sh in $TARGET (starts it, then shuts it down)."
    read -r -p "Continue? [y/N] " a
    [[ $a =~ ^[Yy] ]] || {{ echo "cancelled, nothing changed"; exit 1; }}
fi
{m.v}_run "$TARGET"
qvm-shutdown --wait "$TARGET"
''' + done_block(m)
        return path, s

    s = header(path, m, "Sets everything up from dom0 on Qubes OS 4.3, WITHOUT minimal templating\n"
               "# (for that, use setup-dom0-templating.sh). Run as your normal user. Safe to re-run.") + f'''#
# Makes:
#   {STANDALONE_BASE}: base template, downloaded if missing, never changed
{describe_qubes(m, STANDALONE_PREFIX)}{EXISTING_RULES}
set -euo pipefail

# ------------------------------------------------------------------ CONFIG
BASE={STANDALONE_BASE}
TPL_PREFIX={STANDALONE_PREFIX}
{m.config()}# ------------------------------------------------------------------ END CONFIG
WARNED=0
declare -A KEEP=()

{embed("S_" + m.v, m.setup)}{read("tools/dom0-lib.sh")}{m.funcs(False)}
[ "$(id -u)" -ne 0 ] || die "run as your normal user in dom0, not as root"
command -v qvm-prefs >/dev/null || die "run this in dom0"
valid_name "$BASE"; {m.v}_check
if exists "$BASE" && [ "$(kind "$BASE")" != TemplateVM ]; then
    die "'$BASE' exists but is a $(describe "$(kind "$BASE")"), not a template. Change BASE at the top."
fi
''' + confirm_block(m, [
        "make or update its templates (cloned from $BASE, downloaded if missing)",
        "remove and make again its named disposables and disposable templates",
        "make its app qubes, or keep them with your data and set their settings",
        "keep any qube of the wrong kind as <name>-old",
        "write its dom0 policy (needs sudo)" if m.policy else "",
    ]) + f'''
say "== $BASE"
if exists "$BASE"; then say "   present"
else
    say "   not installed: downloading it (this takes a while)"
    qvm-template install "$BASE"
    exists "$BASE" || die "$BASE could not be installed"
fi
say "== existing qubes"
{m.v}_clear
say "== templates and qubes"
{m.v}_make
say "== settings and setup inside the qubes"
{m.v}_finish
''' + done_block(m)
    return path, s


def module_dom0_templating(m):
    path = f"{m.folder}/setup-dom0-templating.sh"
    s = header(path, m, "Adds this to MINIMAL TEMPLATING (github.com/ridgeforrester1/qubes) from dom0.\n"
               "# Run as your normal user, after setup-all-in-one.sh or templating/install.sh. Safe to re-run.") + f'''#
# setup-all-in-one.sh includes this module when you answer yes to its question,
# so its packages stay in master.dnf on later re-runs. If you set it up with this
# script instead, re-run this script after re-running setup-all-in-one.sh.
#
# Makes (templates built by minimal-templating from your base):
{describe_qubes(m, MT_PREFIX)}{EXISTING_RULES}
set -euo pipefail

# ------------------------------------------------------------------ CONFIG
TPL_PREFIX={MT_PREFIX}
{m.config()}# ------------------------------------------------------------------ END CONFIG
CONF=~/.config/minimal-templating/templates.conf
MT=~/.local/bin/minimal-templating
UNIT=minimal-templating-listen.service
D=/etc/minimal-templating
WARNED=0
declare -A KEEP=()

{embed("S_" + m.v, m.setup)}{read("tools/dom0-lib.sh")}{m.funcs(True)}
[ "$(id -u)" -ne 0 ] || die "run as your normal user in dom0, not as root"
command -v qvm-prefs >/dev/null || die "run this in dom0"
[ -x "$MT" ] && [ -f "$CONF" ] || die "minimal templating is not set up (missing $MT or $CONF).
Run setup-all-in-one.sh first, or use setup-dom0.sh (no minimal templating)."
BASE=$(conf_base)
exists "$BASE" || die "base template $BASE not found"
{m.v}_check
''' + confirm_block(m, [
        "install its packages in $BASE, add them to master.dnf and write its lists",
        "add its sections to templates.conf and build them",
        "remove and make again its named disposables and disposable templates",
        "make its app qubes, or keep them with your data and set their settings",
        "keep any qube of the wrong kind as <name>-old",
        "write its dom0 policy (needs sudo)" if m.policy else "",
    ]) + f'''pause_watcher
say "== $BASE"
{m.v}_base
qvm-shutdown --wait "$BASE"
say "   $BASE shut down, disk saved"
say "== templates.conf"
{m.v}_conf
say "== existing qubes"
{m.v}_clear
say "== build"
"$MT" $(for t in $({m.v}_templates); do printf -- '--only %s ' "$t"; done) || die "build failed: see ~/.local/state/minimal-templating/minimal-templating.log"
say "== settings and setup inside the qubes"
{m.v}_finish
''' + done_block(m)
    return path, s


# ================================================================== templating + all-in-one
def templating_dom0(all_in_one, modules):
    name = "setup-all-in-one.sh" if all_in_one else "templating/install.sh"
    mods = sorted((m for m in modules if m.question), key=lambda m: (m.order, m.name)) if all_in_one else []
    n_q = len(mods) + 1
    if all_in_one:
        desc = ("set up minimal templating plus any of the modules in this repository,\n"
                "# from scratch or as an update.")
