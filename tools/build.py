#!/usr/bin/env python3
"""Regenerate every setup script from the plain source files beside them.

The setup scripts embed those files verbatim, so what you audit is what runs:

    python3 tools/build.py          # rewrite the generated setup scripts
    python3 tools/build.py --check  # exit 1 if any generated script is out of date

Generated (do not edit by hand; edit the sources and rebuild):
    sys-net-wifi/setup.sh        <- sys-net-wifi/wifi-persistence.rc
    sys-vpn-wireguard/setup.sh   <- sys-vpn-wireguard/vpn-autoconnect.rc
    flatpak/setup.sh             <- flatpak/05-flatpak-update.sh, flatpak/flatpak-proxy.sh
    templating/install.sh        <- templating/* (scripts, config, lists)
    setup-all-in-one.sh          <- templating/* + the three setup.sh above
"""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATED_NOTE = "# GENERATED by tools/build.py from the files beside it: edit those, then rebuild.\n"


def src(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        content = f.read()
    assert content.endswith("\n"), f"{rel} must end with a newline"
    return content


def embed(var, content):
    d = f"__END_{var}__"
    assert d not in content, var
    return f"{var}=$(cat <<'{d}'\n{content}{d}\n)\n"


# ============================================================ module: sys-net Wi-Fi
WIFI = r'''#!/bin/bash
# sys-net-wifi/setup.sh - remember Wi-Fi networks in a disposable net qube.
@@NOTE@@#
# Run as root in the net qube's DISPOSABLE TEMPLATE (e.g. sys-net-dvm), not in
# the disposable itself. Either, inside the disposable template:
#   sudo bash setup.sh [--qube sys-net]
# or from dom0, after copying setup.sh into the disposable template:
#   qvm-run -u root -p sys-net-dvm 'bash /home/user/QubesIncoming/<qube>/setup.sh'
#
# Options:
#   --qube NAME   name of the net qube that should load the networks (default sys-net)
#
# Installs (re-running replaces the script and keeps saved networks):
#   /rw/config/rc.local-early.d/wifi-persistence.rc   0755  restores networks at boot
#   /usr/local/etc/nm-connections/                    0700  saved .nmconnection files
#
# Needs NetworkManager in the template (qubes-core-agent-network-manager).

set -euo pipefail

QUBE=sys-net
while [ $# -gt 0 ]; do
    case "$1" in
        --qube) QUBE=${2:?--qube needs a name}; shift 2 ;;
        -h|--help) sed -n '2,20p' "$0" 2>/dev/null || true; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done
[[ $QUBE =~ ^[A-Za-z0-9][A-Za-z0-9_-]*$ ]] || { echo "invalid qube name: $QUBE" >&2; exit 2; }
[ "$(id -u)" -eq 0 ] || { echo "run as root (see the top of this file)" >&2; exit 1; }
if [ "$(qubesdb-read /qubes-vm-persistence 2>/dev/null || true)" = none ]; then
    echo "this is a disposable: anything installed here is lost at shutdown." >&2
    echo "run it in the disposable template instead (e.g. sys-net-dvm)." >&2
    exit 1
fi
command -v nmcli >/dev/null || echo "WARN: nmcli not found: the template needs NetworkManager" >&2

@@PAYLOAD@@
SCRIPT=${SCRIPT/net_qube=\"sys-net\"/net_qube=\"$QUBE\"}

install -d -m 0755 /rw/config/rc.local-early.d
dest=/rw/config/rc.local-early.d/wifi-persistence.rc
printf '%s\n' "$SCRIPT" > "$dest.new"
chown root:root "$dest.new"; chmod 0755 "$dest.new"; mv -f "$dest.new" "$dest"
install -d -m 0700 -o root -g root /usr/local/etc/nm-connections

echo "installed $dest (net qube: $QUBE) and /usr/local/etc/nm-connections/"
echo "save a network into it from dom0 after joining it in $QUBE:"
echo "  f='<network name>.nmconnection'"
echo "  qvm-run -u root --pass-io $QUBE \"cat '/etc/NetworkManager/system-connections/\$f'\" |"
echo "    qvm-run -u root --pass-io $(qubesdb-read /name 2>/dev/null || echo '<this dvm>') \"umask 077; cat > '/usr/local/etc/nm-connections/\$f'\""
'''

