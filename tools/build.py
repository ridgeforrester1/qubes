# ================================================================== main
def generated():
    out = {}
    folders = sorted(d for d in os.listdir(ROOT)
                     if os.path.isfile(os.path.join(ROOT, d, "module.toml")))
    modules = [Module(f) for f in folders]
    for m in modules:
        out[f"{m.folder}/setup.sh"] = m.setup
        if "dom0" in m.versions:
            p, s = module_dom0(m)
            out[p] = s
        if "dom0-templating" in m.versions:
            assert m.qubes, f"{m.folder}: dom0-templating needs [[qube]] entries"
            p, s = module_dom0_templating(m)
            out[p] = s
    if os.path.isdir(os.path.join(ROOT, "templating")):
        for flag in (False, True):
            n, c = templating_dom0(flag, modules)
            out[n] = c
    return out


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, content in generated().items():
        path = os.path.join(ROOT, rel)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != content:
            stale.append(rel)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
                os.chmod(path, 0o755)
    if check:
        if stale:
            print("out of date (run python3 tools/build.py):", " ".join(stale))
            return 1
        print("all generated scripts are up to date")
        return 0
    print("wrote:", " ".join(stale) if stale else "nothing (all up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
